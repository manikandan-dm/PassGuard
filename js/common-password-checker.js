export function checkCommonPassword(password, weaknesses = []) {
  validatePassword(password);
  const exactMatch = isExactCommonPassword(password);
  const relevant = new Set([
    'common-password',
    'sequence',
    'keyboard',
    'repeated-character',
    'repeated-section',
    'repeated-words',
    'predictable-substitution',
    'dictionary-word',
    'predictable-combination',
    'single-character',
    'familiar-phrase',
  ]);
  return {
    status: 'checked',
    exactMatch,
    listSize: COMMON_PASSWORDS.length,
    label: exactMatch ? 'Exact match in the local list' : 'Not found in the local list',
    heuristicWarnings: weaknesses
      .filter((item) => relevant.has(item.code))
      .map(({ code, title, explanation }) => ({ code, title, explanation })),
    limitation:
      'This is a small, case-sensitive, hand-curated example list. Absence is not evidence that a password is uncommon or safe.',
  };
}
